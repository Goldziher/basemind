"""Fail when a vendored crate's source differs from what crates.io serves for its version.

Usage:
    python3 scripts/check_vendored_crates.py [--offline-ok]

basemind depends on forks vendored under ``crates/`` (path + version dependencies). When basemind is
published, crates.io resolves each of them by VERSION, not by path. If a fork changed after its
version was published, the published basemind builds against the stale registry copy: the publish
step reads "already exists" as success, and ``cargo publish`` verifies default features only, so the
break surfaces only when a user builds ``--features full``. This compares, for every vendored crate
basemind depends on, the files ``cargo package --list`` would ship against the ``.crate`` crates.io
serves for the same version. A difference fails until the crate's version is bumped. A version
crates.io does not have yet passes (the release publishes it first).

``Cargo.toml`` is compared through the ``Cargo.toml.orig`` crates.io keeps, parsed, with the
``[package]`` keys that only describe the crate (homepage, include, ...) left out: those never change
what a dependent compiles. A file the published crate has and the tree no longer ships counts only
under ``src/`` or as ``build.rs``. The normalized ``Cargo.toml``, ``Cargo.lock`` and
``.cargo_vcs_info.json`` are generated by ``cargo package`` and are not compared. ``--offline-ok`` turns a network failure into a warning; without it every failure to
reach crates.io fails the check.
"""

from __future__ import annotations

import io
import subprocess
import sys
import tarfile
import tomllib
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Vendored crates the published `basemind` crate depends on, in publish order.
CRATES = ["lsp-positions", "tree-sitter-graph", "stack-graphs", "tree-sitter-stack-graphs", "basemind-agents"]
GENERATED = {"Cargo.toml", "Cargo.lock", ".cargo_vcs_info.json"}
DESCRIPTIVE_PACKAGE_KEYS = {
    "authors",
    "categories",
    "description",
    "documentation",
    "exclude",
    "homepage",
    "include",
    "keywords",
    "readme",
    "repository",
}
USER_AGENT = "basemind-release-gate (vendored crate drift check)"


def package_files(name: str) -> list[str]:
    """Files ``cargo package`` would ship for ``name``, relative to its crate directory."""
    out = subprocess.run(
        ["cargo", "package", "--list", "--allow-dirty", "-p", name],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return [line.strip() for line in out.splitlines() if line.strip()]


def fetch_crate(name: str, version: str) -> bytes | None:
    """The ``.crate`` archive crates.io serves, or ``None`` when that version is not published."""
    url = f"https://static.crates.io/crates/{name}/{name}-{version}.crate"
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.read()
    except urllib.error.HTTPError as error:
        if error.code in (403, 404):
            return None
        raise


def published_files(archive: bytes, prefix: str) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as tar:
        for member in tar.getmembers():
            if not member.isfile() or not member.name.startswith(prefix):
                continue
            handle = tar.extractfile(member)
            if handle is not None:
                files[member.name[len(prefix) :]] = handle.read()
    return files


def manifest_semantics(text: str) -> dict:
    """A manifest without the ``[package]`` keys that never change what a dependent compiles."""
    manifest = tomllib.loads(text)
    package = manifest.get("package", {})
    manifest["package"] = {k: v for k, v in package.items() if k not in DESCRIPTIVE_PACKAGE_KEYS}
    return manifest


def builds_from(rel: str) -> bool:
    return rel.startswith("src/") or rel == "build.rs"


def drift(crate_dir: str) -> tuple[str, str, list[str] | None]:
    """(package name, version, differences or ``None`` when the version is unpublished)."""
    manifest = tomllib.loads((ROOT / "crates" / crate_dir / "Cargo.toml").read_text(encoding="utf-8"))
    name, version = manifest["package"]["name"], manifest["package"]["version"]
    archive = fetch_crate(name, version)
    if archive is None:
        return name, version, None
    remote = published_files(archive, f"{name}-{version}/")
    local_names = set(package_files(name))
    differences: list[str] = []
    compared = 0
    for rel in sorted(local_names | set(remote)):
        if rel in GENERATED:
            continue
        source = ROOT / "crates" / crate_dir / ("Cargo.toml" if rel == "Cargo.toml.orig" else rel)
        if rel not in remote:
            differences.append(f"{rel}: in the tree, not in the published {version}")
        elif rel not in local_names:
            if builds_from(rel):
                differences.append(f"{rel}: in the published {version}, gone from the tree")
            continue
        elif rel == "Cargo.toml.orig":
            published = manifest_semantics(remote[rel].decode("utf-8"))
            if manifest_semantics(source.read_text(encoding="utf-8")) != published:
                differences.append(f"Cargo.toml: dependencies or build settings differ from the published {version}")
        elif source.read_bytes() != remote[rel]:
            differences.append(f"{rel}: content differs from the published {version}")
        compared += 1
    if compared == 0:
        differences.append("compared no files: the package listing or the archive is empty")
    return name, version, differences


def main(argv: list[str]) -> int:
    offline_ok = "--offline-ok" in argv
    failed = 0
    for crate_dir in CRATES:
        try:
            name, version, differences = drift(crate_dir)
        except (urllib.error.URLError, TimeoutError) as error:
            level = "warning" if offline_ok else "error"
            print(f"::{level}::{crate_dir}: could not reach crates.io: {error}")
            failed += 0 if offline_ok else 1
            continue
        if differences is None:
            print(f"{name} {version}: not on crates.io yet; the release publishes it")
        elif differences:
            failed += 1
            print(f"::error::{name} {version} differs from the crates.io copy of the same version; bump its")
            print(f"  version in crates/{crate_dir}/Cargo.toml and in every dependent's requirement:")
            for line in differences:
                print(f"  {line}")
        else:
            print(f"{name} {version}: identical to crates.io")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
